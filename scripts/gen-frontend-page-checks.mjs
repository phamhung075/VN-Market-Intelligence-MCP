// ---------------------------------------------------------------------------
// Build capability groups
// ---------------------------------------------------------------------------
function buildCapability(page) {
  const routeFile = `apps/frontend/app/routes/dashboard.${page.slug}.tsx`;
  const slugPath = page.slug === "_index" ? "" : page.slug.replace(/\$reportId/, ":reportId");
  return {
    cap_id: `CAP-FE-PAGE-${page.slug.toUpperCase().replace(/[._$]/g, "-")}`,
    title: `Page: /dashboard/${slugPath} — ${page.viName}`,
    service: "frontend",
    deploy_status: "DEPLOYED",
    rolls_up_functions: [routeFile, page.endpoint],
    checks: page.checks,
  };
}

// ---------------------------------------------------------------------------
// Load, transform, recompute, write
// ---------------------------------------------------------------------------
const doc = JSON.parse(readFileSync(ARTIFACT, "utf-8"));

// 1. Normalize legacy NEEDS-REVIEW (hyphen) → NEEDS_REVIEW (underscore) to match
//    the consumer route CheckStatus enum (dashboard.quality-audit.tsx).
let normalized = 0;
for (const cap of doc.capabilities) {
  for (const c of cap.checks) {
    if (c.status === "NEEDS-REVIEW") {
      c.status = "NEEDS_REVIEW";
      normalized++;
    }
  }
}

// 2. Idempotency — drop any prior CAP-FE-PAGE-* groups.
const before = doc.capabilities.length;
doc.capabilities = doc.capabilities.filter((c) => !String(c.cap_id).startsWith("CAP-FE-PAGE-"));
const removed = before - doc.capabilities.length;

// 3. Append fresh per-page capability groups.
const newCaps = PAGES.map(buildCapability);
doc.capabilities.push(...newCaps);

// 4. Recompute summary FROM rows (lowercase keys — consumer contract).
const allChecks = doc.capabilities.flatMap((c) => c.checks);
const count = (s) => allChecks.filter((c) => c.status === s).length;
doc.summary = {
  pass: count("PASS"),
  warn: count("WARN"),
  fail: count("FAIL"),
  info: count("INFO"),
  needs_review: count("NEEDS_REVIEW"),
  total: allChecks.length,
};

// 5. overall — HEALTHY unless any FAIL.
doc.overall = doc.summary.fail > 0 ? "DEGRADED" : "HEALTHY";

// 6. Provenance metadata.
doc._updated_at = new Date().toISOString();
doc._updated_by = "po";

writeFileSync(ARTIFACT, JSON.stringify(doc, null, 2) + "\n");

